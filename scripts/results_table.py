"""Write the README results table from the latest eval result files.

    python scripts/results_table.py            # rewrites the block between RESULTS markers in README.md

Columns: baseline and final, offline (replay) and with a live model (anthropic or
bedrock, whichever has results). A missing run prints PENDING. Nothing in the
table is typed by hand.
"""
from __future__ import annotations

import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def latest(pipeline: str, split: str, backends: list[str]) -> dict | None:
    names = [pipeline] + (["v5_rules"] if pipeline == "final" else [])
    files = []
    for b in backends:
        for n in names:
            files += glob.glob(str(ROOT / f"evals/results/*_{n}_{split}_{b}.json"))
    if not files:
        return None
    return json.loads(Path(sorted(files, key=lambda f: Path(f).name)[-1]).read_text())


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}"


ROWS = [
    ("Field F1 (all fields)", lambda m: pct(m["fields"]["overall"]["f1"])),
    ("Critical-field F1", lambda m: pct(m["fields"]["critical"]["f1"])),
    ("F1 on held-out template C", lambda m: pct(m["fields"]["by_template"].get("C", {}).get("f1"))),
    ("Appetite decision accuracy", lambda m: pct(m["decision"]["accuracy"])),
    ("Declines predicted as accept", lambda m: str(m["decision"]["declines_predicted_accept"])),
    ("Review-queue rate", lambda m: pct(m["review"]["review_rate"])),
    ("Silent critical-error rate", lambda m: pct(m["review"]["silent_critical_error_rate"])),
    ("Conflict detection P / R", lambda m: f"{pct(m['conflicts']['precision'])} / {pct(m['conflicts']['recall'])}"),
    ("Latency p50 / p95 (s; offline columns exclude LLM)", lambda m: f"{m['latency_ms']['p50'] / 1000:.2f} / {m['latency_ms']['p95'] / 1000:.1f}"),
    ("LLM latency per submission (s)", lambda m: f"{m['latency_ms']['llm_recorded_mean'] / 1000:.1f}"),
    ("LLM cost per submission (USD)", lambda m: f"{m['cost']['usd_per_submission']:.3f}"),
    ("LLM calls per submission", lambda m: f"{sum(m['cost']['llm_calls_by_source'].values()) / m['n_submissions']:.1f}"),
]


def table(split: str) -> str:
    cols = [("Baseline, offline", "baseline", ["replay"]), ("Final, offline", "final", ["replay"]),
            ("Baseline, Claude", "baseline", ["anthropic", "bedrock"]), ("Final, Claude", "final", ["anthropic", "bedrock"])]
    runs = [latest(p, split, b) for _, p, b in cols]
    lines = [f"| {split} split ({runs[1]['meta']['n'] if runs[1] else '?'} submissions) | " + " | ".join(c[0] for c in cols) + " |",
             "|---|" + "---|" * len(cols)]
    # Live runs may cover the test split only (the dev split was used for development): say so, not PENDING.
    skipped = split == "dev" and runs[1] is not None and any(
        latest(p, "test", b) for _, p, b in cols[2:]) and not any(runs[2:])
    missing = "not run" if skipped else "**PENDING**"
    lines.append("| Model | " + " | ".join(
        "—" if r is None else ("none (offline)" if r["meta"]["backend"] == "replay" else r["meta"].get("model", "?"))
        for r in runs) + " |")
    for name, f in ROWS:
        cells = []
        for r in runs:
            if r is None:
                cells.append(missing)
                continue
            try:
                cells.append(f(r["metrics"]))
            except (KeyError, ZeroDivisionError, TypeError):
                cells.append("n/a")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    if skipped:
        lines.append("\n<sub>Live runs cover the held-out test split only; the dev split was used while building.</sub>")
    shas = sorted({r["meta"]["git_sha"] for r in runs if r})
    lines.append(f"\n<sub>Generated by scripts/results_table.py from evals/results/ (git {', '.join(shas)}).</sub>")
    return "\n".join(lines)


def main() -> None:
    block = "\n\n".join(table(s) for s in ("test", "dev"))
    text = README.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), f"{START}\n{block}\n{END}", text, flags=re.S)
    README.write_text(new)
    print(block)


if __name__ == "__main__":
    main()
